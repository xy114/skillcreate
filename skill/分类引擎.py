"""
关键词分类引擎 —— 悟空工作流核心逻辑的 Python 验证版本

用于验证分类规则的正确性，并作为悟空工作流节点配置的逻辑参考。
悟空平台的工作流节点将基于此脚本中定义的规则进行配置。
"""

import json
import csv
import sys
from pathlib import Path

# ============================================================
# 加载词库
# ============================================================

SKILL_DIR = Path(__file__).parent
词库_DIR = SKILL_DIR / "词库"

def 加载_json(文件名: str) -> dict:
    """加载词库 JSON 文件"""
    with open(词库_DIR / 文件名, encoding="utf-8") as f:
        return json.load(f)

品牌竞品词库 = 加载_json("品牌竞品词库.json")
属性词库 = 加载_json("属性词库.json")
品类词库 = 加载_json("品类词库.json")
场景信号词库 = 加载_json("场景信号词库.json")

# 展平词库为集合，方便快速匹配
品牌词集合 = set(w.lower() for w in 品牌竞品词库["品牌词"])
竞品词集合 = set(w.lower() for w in 品牌竞品词库["竞品词"])
品类词集合 = set(w.lower() for w in 品类词库["品类词列表"])

# 属性词按维度分别展平
功能词集合 = set(w.lower() for w in 属性词库["属性维度"]["功能属性"]["词列表"])
规格词集合 = set(w.lower() for w in 属性词库["属性维度"]["规格属性"]["词列表"])
人群词集合 = set(w.lower() for w in 属性词库["属性维度"]["人群属性"]["词列表"])
场景属性集合 = set(w.lower() for w in 属性词库["属性维度"]["场景属性"]["词列表"])

# 场景信号词展平
痛点信号词集合 = set(w.lower() for w in 场景信号词库["信号词"]["痛点解决型"]["词列表"])
场景适配词集合 = set(w.lower() for w in 场景信号词库["信号词"]["场景适配型"]["词列表"])
时效需求词集合 = set(w.lower() for w in 场景信号词库["信号词"]["时效需求型"]["词列表"])
所有信号词集合 = 痛点信号词集合 | 场景适配词集合 | 时效需求词集合

# ============================================================
# 分类引擎
# ============================================================

def 子串匹配(关键词: str, 词集合: set) -> set:
    """
    检查词集合中哪些词作为子串出现在关键词中。
    中文关键词无空格分隔，必须用子串匹配而非分词后集合交集。
    """
    关键词小写 = 关键词.lower()
    return {词 for 词 in 词集合 if 词 in 关键词小写}


def 分类关键词(关键词: str) -> tuple:
    """
    对单个关键词进行分类
    返回: (分类结果, 属性标签列表)

    使用子串匹配处理中文复合关键词（如"金色摆件"中匹配"摆件"品类词和"金色"功能词）。
    """
    # ---- 第 1 步: 品牌/竞品词匹配 ----
    命中品牌 = 子串匹配(关键词, 品牌词集合)
    if 命中品牌:
        return ("品牌词", [])

    命中竞品 = 子串匹配(关键词, 竞品词集合)
    if 命中竞品:
        return ("竞品词", [])

    # ---- 第 2 步: 属性词匹配 ----
    命中维度 = []
    属性标签 = []

    命中功能 = 子串匹配(关键词, 功能词集合)
    if 命中功能:
        命中维度.append("功能属性")
        属性标签.append(f"功能:{','.join(sorted(命中功能))}")

    命中规格 = 子串匹配(关键词, 规格词集合)
    if 命中规格:
        命中维度.append("规格属性")
        属性标签.append(f"规格:{','.join(sorted(命中规格))}")

    命中人群 = 子串匹配(关键词, 人群词集合)
    if 命中人群:
        命中维度.append("人群属性")
        属性标签.append(f"人群:{','.join(sorted(命中人群))}")

    命中场景 = 子串匹配(关键词, 场景属性集合)
    if 命中场景:
        命中维度.append("场景属性")
        属性标签.append(f"场景:{','.join(sorted(命中场景))}")

    命中信号词 = 子串匹配(关键词, 所有信号词集合)
    维度数 = len(命中维度)

    # ≥2 个属性维度 → 二级属性词
    if 维度数 >= 2:
        return ("二级属性词", 属性标签)

    # 1 个属性维度 + 场景/痛点信号词 → 三级场景词
    if 维度数 == 1 and 命中信号词:
        return ("三级场景词", 属性标签)

    # 仅 1 个属性维度 → 二级属性词
    if 维度数 == 1:
        return ("二级属性词", 属性标签)

    # 仅命中信号词，无属性词 → 三级场景词
    if 命中信号词:
        return ("三级场景词", [])

    # ---- 第 3 步: 纯品类词判定 ----
    命中品类 = 子串匹配(关键词, 品类词集合)
    if 命中品类:
        return ("一级核心词", [])

    # ---- 第 4 步: 相关性兜底 ----
    return ("不相关/宽泛词", [])


def 计算建议动作(分类: str, 词频: int, 搜索量_str: str) -> str:
    """基于分类结果和指标建议投放策略"""
    if 分类 in ("品牌词", "竞品词"):
        return "建议投放"
    if 分类 == "不相关/宽泛词":
        return "建议否定"
    if 分类 == "一级核心词":
        return "仅Listing嵌入"
    if 分类 in ("二级属性词", "三级场景词"):
        return "建议投放"
    return "待判定"


def 处理关键词表(输入_csv路径: str, 输出_csv路径: str) -> dict:
    """读取原始 CSV，逐词分类，输出结构化结果 CSV，返回统计摘要"""

    seen = {}

    with open(输入_csv路径, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        raw_rows = list(reader)

    for row in raw_rows:
        kw = row["关键词"].strip().lower()
        if kw not in seen:
            seen[kw] = {
                "关键词": row["关键词"].strip(),
                "搜索量": row.get("搜索量", ""),
                "竞争度": row.get("竞争度", ""),
                "PPC竞价(USD)": row.get("PPC竞价(USD)", ""),
                "词频": 1
            }
        else:
            seen[kw]["词频"] += 1

    # 逐词分类
    结果 = []
    统计 = {
        "总词数": len(raw_rows),
        "去重后": len(seen),
        "一级核心词": 0,
        "二级属性词": 0,
        "三级场景词": 0,
        "品牌词": 0,
        "竞品词": 0,
        "不相关/宽泛词": 0,
        "建议否定词": 0,
    }

    for kw, info in seen.items():
        分类, 属性标签 = 分类关键词(kw)
        建议动作 = 计算建议动作(分类, info["词频"], info["搜索量"])

        if 分类 == "一级核心词":
            统计["一级核心词"] += 1
        elif 分类 == "二级属性词":
            统计["二级属性词"] += 1
        elif 分类 == "三级场景词":
            统计["三级场景词"] += 1
        elif 分类 == "品牌词":
            统计["品牌词"] += 1
        elif 分类 == "竞品词":
            统计["竞品词"] += 1
        elif 分类 == "不相关/宽泛词":
            统计["不相关/宽泛词"] += 1
            if 建议动作 == "建议否定":
                统计["建议否定词"] += 1

        结果.append({
            "关键词": info["关键词"],
            "分类": 分类,
            "属性标签": "; ".join(属性标签) if 属性标签 else "-",
            "词频": str(info["词频"]),
            "建议动作": 建议动作,
            "搜索量": info["搜索量"],
            "竞争度": info["竞争度"],
            "PPC竞价(USD)": info["PPC竞价(USD)"],
        })

    # 写入输出 CSV
    输出列 = ["关键词", "分类", "属性标签", "词频", "建议动作", "搜索量", "竞争度", "PPC竞价(USD)"]
    with open(输出_csv路径, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=输出列)
        writer.writeheader()
        writer.writerows(结果)

    return 统计


def 生成群消息摘要(统计: dict, 类目名: str) -> str:
    """根据统计结果生成钉钉群消息摘要"""
    有效词 = 统计["去重后"] - 统计["不相关/宽泛词"]
    return f"""📊 关键词整理完成 | {类目名}

━━ 统计 ━━
总词数：{统计['总词数']} → 去重后：{统计['去重后']} → 有效词：{有效词}

📌 一级核心词：{统计['一级核心词']} 个（品类认知类）
🎯 二级属性词：{统计['二级属性词']} 个（主力投放）
💰 三级场景词：{统计['三级场景词']} 个（高转化）
🏷 品牌/竞品词：{统计['品牌词'] + 统计['竞品词']} 个
✂ 建议否定词：{统计['建议否定词']} 个"""


